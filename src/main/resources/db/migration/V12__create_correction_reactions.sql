-- 교정에 대한 반응(지금은 작성자가 교정자에게 보내는 '고마워요'만). 종류를 늘릴 때는 check 제약에 값만 추가한다.
create table correction_reactions (
    id bigint generated by default as identity primary key,
    correction_id bigint not null references corrections (id) on delete cascade,
    sender_id bigint not null references users (id) on delete cascade,
    type varchar(20) not null,
    read_at timestamptz,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    constraint uk_correction_reactions_correction_sender_type unique (correction_id, sender_id, type),
    constraint ck_correction_reactions_type check (type in ('THANKS'))
);
