create table corrections (
    id bigint generated by default as identity primary key,
    request_id bigint not null references correction_requests (id) on delete cascade,
    corrector_id bigint not null references users (id) on delete cascade,
    comment varchar(1000) not null,
    read_at timestamptz,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    constraint uk_corrections_request unique (request_id)
);

create index idx_corrections_corrector_id on corrections (corrector_id, id desc);

create table correction_items (
    id bigint generated by default as identity primary key,
    correction_id bigint not null references corrections (id) on delete cascade,
    sentence_id bigint not null references diary_sentences (id) on delete cascade,
    changed boolean not null,
    corrected_content varchar(2000),
    reason varchar(500),
    created_at timestamptz not null,
    updated_at timestamptz not null,
    constraint uk_correction_items_correction_sentence unique (correction_id, sentence_id),
    constraint ck_correction_items_changed check (changed = false or corrected_content is not null)
);
