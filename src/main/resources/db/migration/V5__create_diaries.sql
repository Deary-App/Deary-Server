create table diaries (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users (id) on delete cascade,
    diary_date date not null,
    title varchar(80) not null,
    content varchar(2000) not null,
    language varchar(2) not null,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    constraint uk_diaries_user_diary_date unique (user_id, diary_date),
    constraint ck_diaries_language check (language in ('ko', 'ja', 'en'))
);

create index idx_diaries_created_at on diaries (created_at desc, id desc);
create index idx_diaries_language_created_at on diaries (language, created_at desc, id desc);

create table diary_photos (
    id bigint generated by default as identity primary key,
    diary_id bigint not null references diaries (id) on delete cascade,
    storage_path varchar(255) not null,
    sort_order int not null,
    position_x double precision not null,
    position_y double precision not null,
    scale double precision not null,
    rotation double precision not null,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    constraint uk_diary_photos_diary_sort_order unique (diary_id, sort_order),
    constraint ck_diary_photos_sort_order check (sort_order between 0 and 2)
);

create table diary_sentences (
    id bigint generated by default as identity primary key,
    diary_id bigint not null references diaries (id) on delete cascade,
    sentence_index int not null,
    content varchar(2000) not null,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    constraint uk_diary_sentences_diary_index unique (diary_id, sentence_index)
);

create table correction_requests (
    id bigint generated by default as identity primary key,
    diary_id bigint not null references diaries (id) on delete cascade,
    status varchar(20) not null,
    claimed_by bigint references users (id) on delete set null,
    claim_expires_at timestamptz,
    completed_at timestamptz,
    version bigint not null,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    constraint uk_correction_requests_diary unique (diary_id),
    constraint ck_correction_requests_status check (status in ('OPEN', 'CLAIMED', 'COMPLETED'))
);

create index idx_correction_requests_claimed_by on correction_requests (claimed_by);
