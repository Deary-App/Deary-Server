create table user_blocks (
    id bigint generated by default as identity primary key,
    blocker_id bigint not null references users (id) on delete cascade,
    blocked_id bigint not null references users (id) on delete cascade,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    constraint uk_user_blocks_blocker_blocked unique (blocker_id, blocked_id),
    constraint ck_user_blocks_not_self check (blocker_id <> blocked_id)
);

create index idx_user_blocks_blocked_id on user_blocks (blocked_id, blocker_id);

create table reports (
    id bigint generated by default as identity primary key,
    reporter_id bigint not null references users (id) on delete cascade,
    target_type varchar(20) not null,
    target_id bigint not null,
    target_user_id bigint references users (id) on delete set null,
    reason varchar(20) not null,
    detail varchar(500),
    created_at timestamptz not null,
    updated_at timestamptz not null,
    constraint uk_reports_reporter_target unique (reporter_id, target_type, target_id),
    constraint ck_reports_target_type check (target_type in ('DIARY', 'USER', 'CORRECTION')),
    constraint ck_reports_reason check (reason in ('SPAM', 'ABUSE', 'SEXUAL', 'PERSONAL_INFO', 'OTHER'))
);

create index idx_reports_created_at on reports (created_at desc);
create index idx_reports_target_user_id on reports (target_user_id);
