-- Expo에 보낸 푸시의 접수표(ticket). 약 15분 뒤 전달 결과(receipt)를 조회해 앱이 지워진 기기의 토큰을 정리한다.
-- 토큰이 먼저 지워져도 접수표는 결과 확인 뒤 지우므로 push_tokens를 참조하지 않는다.
create table push_tickets (
    id bigint generated by default as identity primary key,
    ticket_id varchar(64) not null,
    token varchar(255) not null,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    constraint uk_push_tickets_ticket_id unique (ticket_id)
);

create index idx_push_tickets_created_at on push_tickets (created_at);
