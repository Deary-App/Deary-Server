create table terms (
    id bigint generated by default as identity primary key,
    type varchar(30) not null,
    version varchar(20) not null,
    title varchar(100) not null,
    content text not null,
    required boolean not null,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    constraint uk_terms_type_version unique (type, version),
    constraint ck_terms_type check (type in ('SERVICE', 'PRIVACY', 'AGE_OVER_14', 'MARKETING'))
);

create table user_consents (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users (id) on delete cascade,
    terms_id bigint not null references terms (id),
    agreed boolean not null,
    created_at timestamptz not null,
    updated_at timestamptz not null
);

create index idx_user_consents_user_id_terms_id on user_consents (user_id, terms_id);

